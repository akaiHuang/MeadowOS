#!/usr/bin/env python3
"""One native navigation state contract, emitted into both self-contained themes."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent
ROWS = ("list row", "list row.activatable", ".sidebar row", ".sidebar row.activatable", ".sidebar treeview.view", "treeview.sidebar")


def selectors(state=""):
    return ",\n".join(row + state for row in ROWS)


def stylesheet():
    return """/* Generated by sidebar_styles.py; edit the common source. */
/* Replace the inherited dashed default while preserving widget-specific focus. */
*:focus {
  outline-style: solid;
  outline-color: alpha(@meadow_accent,.72);
  -gtk-outline-radius: 6px;
}
/* Native content selections share the same shape as navigation rows. */
""" + ",\n".join(target + state for target in (".view", "treeview.view", "iconview.view", "iconview", ".thunar .view")
                       for state in (":selected", ":selected:hover", ":selected:focus", ":selected:active", ":selected:backdrop", ":selected:backdrop:hover")) + """ {
  border-radius: 8px;
}
""" + selectors() + """ {
  font-size: 14px;
  color: @meadow_fg;
  background-color: transparent;
  background-image: none;
  border: 0;
  border-radius: 8px;
  box-shadow: none;
  outline-style: none;
  outline-width: 0;
  outline-offset: -2px;
  -gtk-outline-radius: 6px;
}
placessidebar.sidebar { padding: 12px; }
.sidebar row, list row { min-height: 32px; padding: 0 12px; }
.sidebar row label, .sidebar row image, list row label, list row image { color: inherit; }
.sidebar treeview.view, treeview.sidebar {
  min-height: 32px;
  -GtkTreeView-vertical-separator: 0;
  -GtkTreeView-horizontal-separator: 24;
}
""" + selectors(":hover:not(:selected):not(:disabled)") + """ {
  background-color: alpha(@meadow_fg,.055);
}
""" + ",\n".join(selectors(state) for state in (":selected", ":selected:hover", ":selected:focus", ":selected:active", ":selected:backdrop", ":selected:backdrop:hover")) + """ {
  background-color: alpha(@meadow_selected,.90);
  background-image: linear-gradient(to bottom, alpha(white,.15), alpha(white,.03));
  color: @meadow_selected_fg;
  border-radius: 8px;
  box-shadow: inset 0 1px alpha(white,.18), inset 0 -1px alpha(@meadow_accent,.06);
}
.sidebar row:selected label, .sidebar row:selected image,
.sidebar row:selected:backdrop label, .sidebar row:selected:backdrop image {
  color: @meadow_selected_fg;
}
""" + selectors(":focus") + """ {
  outline-style: solid;
  outline-width: 1px;
  outline-color: alpha(@meadow_accent,.72);
}
""" + selectors(":focus:backdrop") + """ { outline-width: 0; }
""" + selectors(":disabled") + """ {
  color: @meadow_disabled;
  background-color: transparent;
  background-image: none;
  box-shadow: none;
}
""" + settings_surfaces()


