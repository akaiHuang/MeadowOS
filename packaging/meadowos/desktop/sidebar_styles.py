def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = stylesheet()
    for theme in ("Meadow-Light", "Meadow-Dark"):
        target = ROOT / "themes" / theme / "gtk-3.0/sidebar-states.css"
        if args.check:
            if not target.is_file() or target.read_text() != expected:
                parser.error(f"Shared sidebar styles drifted: {target}")
        else:
            target.write_text(expected)
    print("Verified shared sidebar states" if args.check else "Wrote shared sidebar states")


if __name__ == "__main__":
    main()
