// SamplingPhase is a harness-owned structural hint. It lets local-model
// profiles reduce variance for verification and targeted repair without
// teaching the provider anything about the task's semantic content. The hint
// is never serialized to the OpenAI-compatible backend.
type SamplingPhase string

const (
	SamplingPhaseSolve         SamplingPhase = "solve"
	SamplingPhaseAudit         SamplingPhase = "audit"
	SamplingPhaseAuditRecovery SamplingPhase = "audit_recovery"
	SamplingPhaseRepair        SamplingPhase = "repair"
	SamplingPhaseRecovery      SamplingPhase = "recovery"
	SamplingPhaseFinal         SamplingPhase = "final"
	// Precision is a route-selected, bounded creation phase for literal-copy
	// work. It is not used for research, planning, code generation, or repair.
	SamplingPhasePrecision SamplingPhase = "precision"
)

// ChatRequest deliberately omits the optional OpenAI fields that the legacy
// mlx_lm.server rejects. PresencePenalty is the one backend-scoped exception:
// current vllm-mlx supports it and the Qwen adapter emits it only for profiles
// served through that backend. StripUnsupportedFields still protects the
// legacy map-shaped passthrough path used by serve mode.
type ChatRequest struct {
	Model              string          `json:"model"`
	Messages           []Message       `json:"messages"`
	Tools              []Tool          `json:"tools,omitempty"`
	ToolChoice         any             `json:"tool_choice,omitempty"`
	MaxTokens          *int            `json:"max_tokens,omitempty"`
	Temperature        *float64        `json:"temperature,omitempty"`
	TopP               *float64        `json:"top_p,omitempty"`
	TopK               *int            `json:"top_k,omitempty"`
	Stop               []string        `json:"stop,omitempty"`
	Stream             bool            `json:"stream,omitempty"`
	StreamOptions      *StreamOptions  `json:"stream_options,omitempty"`
	EnableThinking     *bool           `json:"enable_thinking,omitempty"`
	Thinking           *ThinkingConfig `json:"thinking,omitempty"`
	ChatTemplateKwargs map[string]any  `json:"chat_template_kwargs,omitempty"`
	PresencePenalty    *float64        `json:"presence_penalty,omitempty"`
	RepetitionPenalty  *float64        `json:"repetition_penalty,omitempty"`
	ParallelToolCalls  *bool           `json:"parallel_tool_calls,omitempty"`
	// ReasoningEffort is the native SGLang/OpenAI reasoning control. Explicit
	// user overrides and model-family product defaults may both set it.
	ReasoningEffort ReasoningEffort `json:"reasoning_effort,omitempty"`
	// CacheSalt isolates reusable prefixes to one caller-owned agent session.
	// Meadow Core preserves this scope for tool requests; an empty value keeps
	// the conservative per-request isolation policy.
	CacheSalt string `json:"cache_salt,omitempty"`
	// ProtocolRecovery is an internal one-turn hint used after a malformed
	// native tool call. It is never serialized; local-family safety profiles
	// can lower sampling variance without changing the tool or task semantics.
	ProtocolRecovery bool `json:"-"`
	// GuidanceAction is an internal one-turn hint for a controller-locked tool
	// request immediately after accepted user guidance, or its single compact
	// retry. It changes only the bounded decode allowance; the model still
	// authors every tool argument and the field is never serialized.
	GuidanceAction bool `json:"-"`
	// SamplingPhase is set by the agent kernel from its already-observed
	// lifecycle state. The provider uses it only to shape sampling controls.
	SamplingPhase SamplingPhase `json:"-"`
	// UserThinkingMode/UserReasoningEffort are session-owned preferences. They are
	// applied after the model safety profile so an explicit /think command is
	// not silently overwritten by a family default such as Qwen 27B think-off.
	UserThinkingMode    ThinkingMode    `json:"-"`
	UserReasoningEffort ReasoningEffort `json:"-"`
	// StreamedToolDraft asks the local provider transport to keep the registered
	// tool as the execution/schema authority while omitting OpenAI `tools` from
	// the wire request. Some MLX chat templates buffer a large JSON string until
	// its closing brace; a complete tagged call can instead stream incrementally,
	// then be repaired back into this exact registered tool before execution.
	// The field is internal and never reaches the model server.
	StreamedToolDraft string `json:"-"`
}

// ThinkingConfig is DeepSeek's native control, separate from local templates.
type ThinkingConfig struct {
	Type string `json:"type"`
}

// MarshalJSON keeps private reasoning out of ordinary Message serialization.
// Native DeepSeek tool conversations require earlier reasoning across user
// turns, including assistant answers without tool calls. Do not infer or
// manufacture it for imported history or a different model.
func (r ChatRequest) MarshalJSON() ([]byte, error) {
	type plain ChatRequest
	messages := make([]json.RawMessage, len(r.Messages))
	for i, message := range r.Messages {
		body, err := json.Marshal(message)
		if err != nil {
			return nil, err
		}
		if state := r.nativeReasoning(message); state != nil {
			var fields map[string]json.RawMessage
			if err := json.Unmarshal(body, &fields); err != nil {
				return nil, err
			}
			fields["reasoning_content"], _ = json.Marshal(state.Content)
			body, err = json.Marshal(fields)
			if err != nil {
				return nil, err
			}
		}
		messages[i] = body
	}
	return json.Marshal(struct {
		*plain
		Messages []json.RawMessage `json:"messages"`
	}{plain: (*plain)(&r), Messages: messages})
}

func (r ChatRequest) nativeReasoning(message Message) *ProviderReasoning {
	if IsDeepSeekModel(r.Model) && len(r.Tools) > 0 && message.Role == "assistant" &&
		message.ProviderReasoning != nil && message.ProviderReasoning.Model == r.Model {
		return message.ProviderReasoning
	}
	return nil
}

// RequestReasoningTokenEstimate charges only private bytes that this exact
// native request serializes. It exposes a count, never private text, to the
// context admission/atomic history-compaction layer.
func RequestReasoningTokenEstimate(request ChatRequest, message Message) int {
	if state := request.nativeReasoning(message); state != nil {
		return EstimateTextTokens(state.Content)
	}
	return 0
}

// StreamOptions asks OpenAI-compatible servers to emit the terminal usage
// chunk. It is sent only to Meadow Core; legacy mlx_lm servers reject it.
type StreamOptions struct {
	IncludeUsage bool `json:"include_usage"`
}

type Usage struct {
	PromptTokens     int `json:"prompt_tokens"`
	CompletionTokens int `json:"completion_tokens"`
	TotalTokens      int `json:"total_tokens"`
	// ContextPromptTokens is the prompt size of the latest primary model
	// request represented by an aggregated logical-turn usage value. Advisor
	// and recovery inference can increase PromptTokens (cost) without making
	// the live conversation context that large. These fields are harness-only
	// and never cross the provider wire format.
	ContextPromptTokens    int  `json:"-"`
	ContextPromptTokensSet bool `json:"-"`
	// LogicalTurnUsage asks product adapters to persist this aggregate as one
	// standalone logical-turn record. CoveredAssistantCount identifies primary
	// and synthetic Advisor assistant boundaries already included in the total,
	// so legacy usage backfill does not estimate them again.
	LogicalTurnUsage      bool `json:"-"`
	CoveredAssistantCount int  `json:"-"`
	// AssistantUsageCoverage is a compact assistant-boundary bitmap for the
	// logical turn ("1" means the aggregate accounts for that boundary, "0"
	// means its missing provider usage may still be estimated). The prior count
	// tells durable consumers how much of the bitmap preceded the usage record;
	// the remainder applies to assistant records written immediately afterward.
	AssistantUsageCoverage      string `json:"-"`
	AssistantCoveragePriorCount int    `json:"-"`
}

// ContextPromptSize returns the latest primary-request prompt size represented
// by this usage sample. Legacy callers that report one inference per logical
// turn continue to use PromptTokens; aggregated runtimes can keep auxiliary
// inference cost in PromptTokens without inflating the live context meter.
func (u *Usage) ContextPromptSize() (int, bool) {
	if u == nil {
		return 0, false
	}
	if u.ContextPromptTokensSet {
		return u.ContextPromptTokens, true
	}
	return u.PromptTokens, u.PromptTokens > 0
}

type ChatResponse struct {
	Choices []struct {
		Message      Message `json:"message"`
		FinishReason string  `json:"finish_reason"`
	} `json:"choices"`
	Usage *Usage `json:"usage"`
}

type streamChunk struct {
	Choices []struct {
		Delta struct {
			Content          string          `json:"content"`
			ReasoningContent *string         `json:"reasoning_content"`
			Reasoning        *string         `json:"reasoning"`
			ToolCalls        []toolCallDelta `json:"tool_calls"`
		} `json:"delta"`
		FinishReason *string `json:"finish_reason"`
	} `json:"choices"`
	Usage *Usage `json:"usage"`
}

type toolCallDelta struct {
	Index    int    `json:"index"`
	ID       string `json:"id"`
	Type     string `json:"type"`
	Function struct {
		Name      string `json:"name"`
		Arguments string `json:"arguments"`
	} `json:"function"`
}

// mlxUnsupportedFields mirrors MLX_UNSUPPORTED_FIELDS in
// packages/core/src/core/openaiContentGenerator/provider/mlx.ts —
// mlx_lm.server returns HTTP 400 on any of these optional OpenAI keys.
var mlxUnsupportedFields = []string{
	"seed",
	"reasoning_effort",
	"frequency_penalty",
	"presence_penalty",
	"logprobs",
	"top_logprobs",
	"response_format",
	"n",
	"service_tier",
	"store",
	"user",
}

// StripUnsupportedFields removes MLX-rejected keys from a map-shaped request
// (used when proxying arbitrary JSON, e.g. serve mode). Returns the list of
// stripped keys.
func StripUnsupportedFields(req map[string]any) []string {
	var stripped []string
	for _, f := range mlxUnsupportedFields {
		if _, ok := req[f]; ok {
			delete(req, f)
			stripped = append(stripped, f)
		}
	}
	return stripped
}

// MarshalArgs encodes a parsed argument object back into the OpenAI
// arguments wire string.
func MarshalArgs(args map[string]any) string {
	b, err := json.Marshal(args)
	if err != nil {
		return "{}"
	}
	return string(b)
}
