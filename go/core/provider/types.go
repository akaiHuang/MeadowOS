// AttachmentKindPersistedHistory marks image parts reconstructed from a
// durable chat attachment. Request shaping may remove only these parts when a
// conversation is reopened with a text-only model, without silently dropping
// a new user upload that should instead fail normal input validation.
const (
	AttachmentKindPersistedHistory = "persisted_history_image"
	// AttachmentKindToolResult marks a provider-only synthetic copy of pixels
	// produced by a tool. It is deliberately omitted from the wire format and
	// lets context selection distinguish visual evidence from a real user turn.
	AttachmentKindToolResult = "tool_result_image"
)

// MessageContentPart is one OpenAI-compatible multipart chat content item.
// Text-only callers keep using Message.Content; desktop vision prompts set
// ContentParts so the provider serializes content as an array.
type MessageContentPart struct {
	Type           string           `json:"type"`
	Text           string           `json:"text,omitempty"`
	ImageURL       *MessageImageURL `json:"image_url,omitempty"`
	AttachmentKind string           `json:"-"`
	AttachmentName string           `json:"-"`
	PageNumber     int              `json:"-"`
	PageCount      int              `json:"-"`
}

type MessageImageURL struct {
	URL    string `json:"url"`
	Detail string `json:"detail,omitempty"`
}

func (image MessageImageURL) MarshalJSON() ([]byte, error) {
	// "original" selects Meadow's local pixel-normalization bounds. The
	// OpenAI-compatible wire contract accepts auto/low/high, so preserve those
	// pixels and the internal hint while adapting both new and resumed images.
	type wire MessageImageURL
	value := wire(image)
	if value.Detail == "original" {
		value.Detail = "high"
	}
	return json.Marshal(value)
}

// Message is one OpenAI chat-completions message. Content is the canonical
// text view used by routing/history. ContentParts, when present, is the wire
// payload sent to multimodal providers.
type Message struct {
	// MessageID is trusted local presentation identity. It is persisted outside
	// message parts and never sent to, or accepted from, a model provider.
	MessageID    string               `json:"-"`
	Role         string               `json:"role"`
	Content      string               `json:"-"`
	ContentParts []MessageContentPart `json:"-"`
	ToolCalls    []ToolCall           `json:"tool_calls,omitempty"`
	ToolCallID   string               `json:"tool_call_id,omitempty"`
	// RuntimeObservation marks request-local facts generated by the harness.
	// Its user-role wire envelope is not a new user turn for media/history
	// selection. The marker never crosses the wire or becomes durable history.
	RuntimeObservation bool `json:"-"`
	// TaskBoundary is trusted local task-lifecycle metadata, set only by an
	// explicit product IndependentTask action. It is persisted separately by
	// session storage and never marshaled to or accepted from provider JSON.
	TaskBoundary bool `json:"-"`
	// ProviderReasoning is private continuation state, never display content or
	// ordinary message JSON. Only ChatRequest marshaling may put it on the wire,
	// and only for the exact DeepSeek model which produced it.
	ProviderReasoning *ProviderReasoning `json:"-"`
}

type ProviderReasoning struct {
	Model   string `json:"model"`
	Content string `json:"content"`
}

func (m Message) MarshalJSON() ([]byte, error) {
	type wire struct {
		Role       string     `json:"role"`
		Content    any        `json:"content"`
		ToolCalls  []ToolCall `json:"tool_calls,omitempty"`
		ToolCallID string     `json:"tool_call_id,omitempty"`
	}
	var content any = m.Content
	if len(m.ContentParts) > 0 {
		content = m.ContentParts
	}
	return json.Marshal(wire{
		Role:       m.Role,
		Content:    content,
		ToolCalls:  m.ToolCalls,
		ToolCallID: m.ToolCallID,
	})
}

func (m *Message) UnmarshalJSON(data []byte) error {
	m.MessageID = ""
	type wire struct {
		Role             string          `json:"role"`
		Content          json.RawMessage `json:"content"`
		ToolCalls        []ToolCall      `json:"tool_calls,omitempty"`
		ToolCallID       string          `json:"tool_call_id,omitempty"`
		ReasoningContent *string         `json:"reasoning_content"`
	}
	var w wire
	if err := json.Unmarshal(data, &w); err != nil {
		return err
	}
	m.Role = w.Role
	m.ToolCalls = w.ToolCalls
	m.ToolCallID = w.ToolCallID
	m.Content = ""
	m.ContentParts = nil
	m.RuntimeObservation = false
	m.TaskBoundary = false
	m.ProviderReasoning = nil
	if w.ReasoningContent != nil {
		// The response decoder cannot establish provenance; the client assigns
		// the request's verified model before retaining this state.
		m.ProviderReasoning = &ProviderReasoning{Content: *w.ReasoningContent}
	}
	if len(w.Content) == 0 || string(w.Content) == "null" {
		return nil
	}
	var text string
	if err := json.Unmarshal(w.Content, &text); err == nil {
		m.Content = text
		return nil
	}
	var parts []MessageContentPart
	if err := json.Unmarshal(w.Content, &parts); err != nil {
		return err
	}
	m.ContentParts = parts
	m.Content = MessageText(Message{ContentParts: parts})
	return nil
}

func MessageText(m Message) string {
	if strings.TrimSpace(m.Content) != "" {
		return m.Content
	}
	if len(m.ContentParts) == 0 {
		return ""
	}
	var parts []string
	for _, p := range m.ContentParts {
		if p.Type == "text" && strings.TrimSpace(p.Text) != "" {
			parts = append(parts, p.Text)
		}
	}
	return strings.Join(parts, "\n")
}

